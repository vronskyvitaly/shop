import { Body, Controller, Get, HttpCode, Patch, Post, Req, Res, UseGuards } from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiConflictResponse,
  ApiCookieAuth,
  ApiNoContentResponse,
  ApiOkResponse,
  ApiTags,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';
import type { Request, Response } from 'express';
import { CreateUserDto } from '../users/dto/create-user.dto.js';
import { UsersService } from '../users/users.service.js';
import { ACCESS_COOKIE, REFRESH_COOKIE, clearAuthCookies, setAuthCookies } from './auth.cookies.js';
import { AuthService } from './auth.service.js';
import type { AuthUser } from './auth.types.js';
import { CurrentUser } from './current-user.decorator.js';
import { LoginDto } from './dto/login.dto.js';
import { ChangePasswordDto, UpdateProfileDto } from './dto/profile.dto.js';
import { JwtAuthGuard } from './jwt-auth.guard.js';

@ApiTags('auth')
@Controller('auth')
export class AuthController {
  constructor(
    private readonly auth: AuthService,
    private readonly users: UsersService,
  ) {}

  // passthrough: true — we set cookies through res, but the response is still generated by Nest (return)
  @Post('register')
  @ApiConflictResponse({ description: 'Пользователь с таким email уже есть' })
  async register(@Body() dto: CreateUserDto, @Res({ passthrough: true }) res: Response) {
    const { user, tokens } = await this.auth.register(dto);
    setAuthCookies(res, tokens.accessToken, tokens.refreshToken);
    return user;
  }

  @Post('login')
  @HttpCode(200)
  @ApiOkResponse({ description: 'Вход выполнен, токены выставлены в куки' })
  @ApiUnauthorizedResponse({ description: 'Неверный email или пароль' })
  async login(@Body() dto: LoginDto, @Res({ passthrough: true }) res: Response) {
    const { user, tokens } = await this.auth.login(dto);
    setAuthCookies(res, tokens.accessToken, tokens.refreshToken);
    return user;
  }

  @Post('refresh')
  @HttpCode(200)
  @ApiOkResponse({ description: 'Новая пара токенов выставлена в куки' })
  @ApiUnauthorizedResponse({ description: 'Refresh-токен отсутствует, истёк или уже использован' })
  async refresh(@Req() req: Request, @Res({ passthrough: true }) res: Response) {
    try {
      const tokens = await this.auth.refresh(req.cookies?.[REFRESH_COOKIE]);
      setAuthCookies(res, tokens.accessToken, tokens.refreshToken);
      return { message: 'Tokens refreshed' };
    } catch (e) {
      clearAuthCookies(res); // invalid refresh — remove cookies, the client needs to log in again
      throw e;
    }
  }

  @Post('logout')
  @HttpCode(204)
  @ApiNoContentResponse({ description: 'Сессия закрыта, куки очищены' })
  async logout(@Req() req: Request, @Res({ passthrough: true }) res: Response) {
    await this.auth.logout(req.cookies?.[REFRESH_COOKIE]);
    clearAuthCookies(res);
  }

  @Get('me')
  @UseGuards(JwtAuthGuard)
  @ApiCookieAuth(ACCESS_COOKIE)
  @ApiUnauthorizedResponse({ description: 'Нет access-куки или токен истёк' })
  me(@CurrentUser() user: AuthUser) {
    return this.users.getUserById(user.id);
  }

  // Профиль: пока меняется только имя (email — это логин, его смена требует подтверждения почты)
  @Patch('me')
  @UseGuards(JwtAuthGuard)
  @ApiCookieAuth(ACCESS_COOKIE)
  updateMe(@Body() dto: UpdateProfileDto, @CurrentUser() user: AuthUser) {
    return this.users.updateProfile(user.id, dto.name);
  }

  // Смена пароля. Refresh-кука нужна, чтобы оставить открытой текущую сессию и закрыть все остальные
  @Post('password')
  @HttpCode(204)
  @UseGuards(JwtAuthGuard)
  @ApiCookieAuth(ACCESS_COOKIE)
  @ApiBadRequestResponse({ description: 'Неверный текущий пароль' })
  changePassword(@Body() dto: ChangePasswordDto, @CurrentUser() user: AuthUser, @Req() req: Request) {
    return this.auth.changePassword(user.id, dto, req.cookies?.[REFRESH_COOKIE]);
  }
}
